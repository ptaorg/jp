def replace_guideline():
    if not GUIDELINE.exists():
        raise FileNotFoundError(f"not found: {GUIDELINE}")
    text = GUIDELINE.read_text(encoding="utf-8")
    marker = "## 14. 根拠資料の確認"
    if marker not in text:
        raise RuntimeError("docs/guideline.md に第14章マーカーが見つかりません。")
    before = text.split(marker, 1)[0].rstrip() + "\n\n"
    GUIDELINE.write_text(before + CHAPTER14_MD, encoding="utf-8")


def replace_index():
    if not INDEX.exists():
        raise FileNotFoundError(f"not found: {INDEX}")
    text = INDEX.read_text(encoding="utf-8")
    pattern = re.compile(
        r'      <section class="source-box" aria-labelledby="s14">.*?'
        r'      </section>\n\n(?=      <section aria-labelledby="s15">)',
        re.DOTALL,
    )
    new_text, count = pattern.subn(SECTION14_HTML + "\n\n", text)
    if count != 1:
        raise RuntimeError(f"index.html の第14章 section 置換数が {count} 件です。1件でなければ中止します。")
    INDEX.write_text(new_text, encoding="utf-8")


def main():
    replace_guideline()
    replace_index()
    print("第14章の差し替えが完了しました。")
    print("変更ファイル: docs/guideline.md, index.html")


if __name__ == "__main__":
    main()
